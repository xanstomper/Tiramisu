#!/usr/bin/env python3
"""Generate src/trt/gdi_font8x16.h: an 8x16 coverage font for the GDI raster.

The runtime cannot open a font file: the console profile has no font stack and
the offline gate runs with no display. bridge_gdi's DC surface therefore needs
its glyphs compiled in. This script renders ASCII 32..126 plus Latin-1
(U+00A0..U+00FF, the accented letters and symbols desktop UI actually shows)
with DejaVu Sans Mono
(DejaVu license: free redistribution, embedding allowed) at the size that fills
an 8x16 cell with the baseline at 13 (the same ascent bridge_gdi's metrics model
reports for a 16 px cell), and writes 8-bit coverage per pixel.

The generated header is checked in, so the build and the gate never need
Python or a font. Re-run only when changing the face/cell:

    python3 tools/gen_bitmap_font.py

Layout in the header: kGlyphIndex[256] maps a code point to its glyph slot
(255 = not covered), kGlyphCount is the number of slots, kGlyphW=8, kGlyphH=16,
kGlyphAscent=13, kGlyphAdvance=8, kGlyphCoverage[kGlyphCount][16][8].
"""
import os
import sys

from PIL import Image, ImageDraw, ImageFont

RANGES = [(32, 126), (160, 255)]
CELL_W, CELL_H, BASELINE = 8, 16, 13
FONT = "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf"
SIZE = 13
OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                   "src", "trt", "gdi_font8x16.h")


def render(ch, font):
    img = Image.new("L", (CELL_W, CELL_H), 0)
    d = ImageDraw.Draw(img)
    d.text((0, BASELINE), ch, font=font, fill=255, anchor="ls")
    return [[img.getpixel((x, y)) for x in range(CELL_W)]
            for y in range(CELL_H)]


def _index_rows(codepoints):
    """kGlyphIndex rows: 16 code points per line, 255 where absent."""
    slot = {cp: i for i, cp in enumerate(codepoints)}
    rows = []
    for base in range(0, 256, 16):
        vals = [slot.get(c, 255) for c in range(base, base + 16)]
        rows.append("    " + ",".join("%3d" % v for v in vals) + ",")
    return rows


def main():
    font = ImageFont.truetype(FONT, SIZE)
    codepoints = []
    for lo, hi in RANGES:
        codepoints.extend(range(lo, hi + 1))
    glyphs = [render(chr(c), font) for c in codepoints]
    # Space, no-break space and the soft hyphen are legitimately blank; any
    # other blank means the font/anchor does not match the cell.
    blank_ok = {32, 160, 0xAD}
    empty = sum(1 for cp, g in zip(codepoints, glyphs)
                if cp not in blank_ok
                and all(v == 0 for row in g for v in row))
    if empty:
        sys.exit("ERROR: %d glyphs rendered empty (font/anchor mismatch)" % empty)

    lines = [
        "// tiramisu/src/trt/gdi_font8x16.h",
        "// GENERATED by tools/gen_bitmap_font.py -- do not edit by hand.",
        "//",
        "// 8x16 ASCII coverage font used by the GDI raster surface (gdi_raster.cpp).",
        "// Rendered from DejaVu Sans Mono at %d px, baseline %d, cell %dx%d."
        % (SIZE, BASELINE, CELL_W, CELL_H),
        "// DejaVu Fonts license: free use, modification and redistribution,",
        "// including embedding. 0 = no coverage, 255 = full.",
        "#ifndef TIRAMISU_GDI_FONT8X16_H",
        "#define TIRAMISU_GDI_FONT8X16_H",
        "",
        "namespace trt_font8x16 {",
        "constexpr int kGlyphCount = %d;" % len(glyphs),
        "constexpr int kGlyphMissing = 255;",
        "constexpr int kGlyphW = %d;" % CELL_W,
        "constexpr int kGlyphH = %d;" % CELL_H,
        "constexpr int kGlyphAscent = %d;" % BASELINE,
        "constexpr int kGlyphAdvance = %d;" % CELL_W,
        "",
        "// kGlyphIndex[code point] -> glyph slot, kGlyphMissing when absent.",
        "constexpr unsigned char kGlyphIndex[256] = {",
    ] + _index_rows(codepoints) + [
        "};",
        "",
        "// [glyph][row][column]",
        "constexpr unsigned char kGlyphCoverage[kGlyphCount][kGlyphH][kGlyphW] = {",
    ]
    for idx, g in enumerate(glyphs):
        cp = codepoints[idx]
        label = chr(cp) if chr(cp) not in ('"', "\\") else "\\" + chr(cp)
        lines.append("  {  // '%s' (0x%02x)" % (label, cp))
        for row in g:
            lines.append("      {" + ",".join("%3d" % v for v in row) + "},")
        lines.append("  },")
    lines += [
        "};",
        "",
        "}  // namespace trt_font8x16",
        "",
        "#endif",
        "",
    ]
    with open(OUT, "w") as f:
        f.write("\n".join(lines))
    print("wrote %s (%d glyphs)" % (OUT, len(glyphs)))


if __name__ == "__main__":
    main()
