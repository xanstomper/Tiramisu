#!/usr/bin/env bash
# tiramisu/tools/support-matrix.sh
# Generate docs/support-matrix.md from a real corpus run. Every number comes
# from test_corpus --coverage, which classifies every bound import as
# real / recorded / named-silent through trt_symbol_class(). The matrix is
# MEASURED, never hand-written.
set -uo pipefail
here="$(cd "$(dirname "$0")/.." && pwd)"
cd "$here"

# Build + smoke the corpus first; this produces tests/out/test_corpus with
# the exact source set build-test.sh uses and proves the tree still binds.
tools/corpus-smoke.sh >/dev/null || exit 1

out=tests/out
mapfile -t PES < <(find corpus-local -type f 2>/dev/null | \
  grep -iE '\.(exe|dll)$' | sort)
[[ ${#PES[@]} -gt 0 ]] || { echo "ERROR: no corpus PEs found" >&2; exit 1; }

report="$out/support-matrix.txt"
# --gaps implies --coverage, so one run produces both the per-PE scores and the
# aggregated worklist that drives what gets implemented next.
"$out/test_corpus" --gaps "${PES[@]}" >"$report" 2>&1 || exit 1

{
  echo "# Tiramisu — measured support matrix"
  echo
  echo "> Generated by \`tools/support-matrix.sh\` from \`test_corpus --coverage\`."
  echo "> Do not edit by hand. Every row is a real corpus bind simulation."
  echo
  echo "| PE | bound imports | real | recorded | named-silent | unresolved | delay | real % |"
  echo "|---|---:|---:|---:|---:|---:|---:|---:|"
  grep '^COVERAGE ' "$report" | grep -v '^COVERAGE SELFTEST:' | \
  while read -r _ name rest; do
    name=${name%:}
    imports=$(sed -n 's/.*imports=\([0-9]*\).*/\1/p' <<<"$rest")
    real=$(sed -n 's/.*real=\([0-9]*\).*/\1/p' <<<"$rest")
    recorded=$(sed -n 's/.*recorded=\([0-9]*\).*/\1/p' <<<"$rest")
    silent=$(sed -n 's/.*named-silent=\([0-9]*\).*/\1/p' <<<"$rest")
    unres=$(sed -n 's/.*unresolved=\([0-9]*\).*/\1/p' <<<"$rest")
    delay=$(sed -n 's/.*delay=\([0-9]*\).*/\1/p' <<<"$rest")
    pct="0"
    [[ ${imports:-0} -gt 0 ]] && \
      pct=$(awk -v r="${real:-0}" -v t="$imports" 'BEGIN{printf "%.1f", 100*r/t}')
    printf '| %s | %s | %s | %s | %s | %s | %s | %s%% |\n' \
      "$name" "$imports" "$real" "$recorded" "$silent" "${unres:-0}" \
      "$delay" "$pct"
  done
  echo
  echo "## Totals"
  echo '```'
  grep '^COVERAGE ' "$report"
  echo '```'
  echo
  echo "**Reading the numbers:** \`real\` = real semantics; \`recorded\` = the"
  echo "call is accepted and logged but does nothing (e.g. D3D12 draws);"
  echo "\`named-silent\` = a truthful empty answer or named failure (e.g."
  echo "Media Foundation EOS with no frames, Steam auth-only answers)."
  echo "A high \`real %\` predicts a title that reaches gameplay; recorded and"
  echo "named-silent imports are the exact roadmap items for that title."
  echo
  echo "**Delay imports are included.** \`delay=\` counts symbols bound from the"
  echo "delay-load directory (e.g. \`UnityPlayer.dll -> d3d12.dll\`,"
  echo "\`binkw32.dll -> mss32.dll\`); they are also folded into the class counts"
  echo "and the total, matching the loader's eager delay binding."
} >docs/support-matrix.md

echo "wrote docs/support-matrix.md"

# ---- gap worklist ---------------------------------------------------------
# The ranking comes from test_corpus --gaps: one GAP line per module!symbol,
# already sorted by how many titles need it and then by severity. This is the
# file that answers "what do I implement next" from real corpus data.
{
  echo "# Tiramisu — measured gap worklist"
  echo
  echo "> Generated by \`tools/support-matrix.sh\` from \`test_corpus --gaps\`."
  echo "> Do not edit by hand. Each row is a real bind simulation over the corpus."
  echo
  echo "\`unresolved\` = Tiramisu claims the module and does not export the symbol,"
  echo "so the loader would fail. \`named-silent\` = it binds and returns a truthful"
  echo "empty answer or named failure. \`recorded\` = it binds, is logged, and does"
  echo "nothing (e.g. D3D12 draws). Implement top-down: the first row is the single"
  echo "most valuable API in the corpus."
  echo
  echo "| # | symbol | class | titles needing it |"
  echo "|---:|---|---|---:|"
  grep '^GAP ' "$report" | awk '{
    sym=$2; cls=$3; pes=$4;
    sub(/^class=/, "", cls); sub(/^pes=/, "", pes);
    printf "| %d | `%s` | %s | %s |\n", NR, sym, cls, pes;
  }'
  echo
  echo "Total: $(grep -c '^GAP ' "$report") distinct gap symbol(s)."
} >docs/gap-worklist.md
echo "wrote docs/gap-worklist.md"
