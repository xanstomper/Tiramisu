#!/usr/bin/env bash
# tiramisu/tools/pe32-report.sh — run every corpus PE32 entry through the
# clean-room x86 interpreter and record the exact named stop per file.
set -uo pipefail
here="$(cd "$(dirname "$0")/.." && pwd)"
cd "$here"
out=/tmp/opencode/pe32-report
mkdir -p "$out"

clang++ -std=c++17 -O2 -Wall -no-pie -I src/trt \
  tests/test_x86_image.cpp src/trt/x86_32.cpp src/trt/x86_image.cpp \
  src/trt/images.cpp src/trt/pe_loader.cpp src/trt/module_table.cpp \
  src/trt/apiset.cpp src/trt/pe_exports.cpp src/trt/thunk.cpp \
  src/trt/vfs.cpp src/trt/iso.cpp \
  /tmp/opencode/x86-image-test/miniz_tinfl.o -o "$out/test_x86_image" || exit 1

{
  echo '# PE32 execution report (measured)'
  echo
  echo 'Generated by `tools/pe32-report.sh`. Each corpus 32-bit PE is mapped'
  echo 'with `trt_map_pe32` and its entry run through the clean-room x86'
  echo 'interpreter. `run_rc=1` means a clean return; `2` is a named stop.'
  echo
  echo '| PE | traps | rc | EAX | last opcode | fault VA |'
  echo '|---|---:|---:|---:|---|---|'
} >docs/pe32-execution-report.md

for f in $(find corpus-local -type f -iname '*.dll' | sort); do
  bits=$(python3 - "$f" <<'PY'
import sys
sys.path.insert(0,'tools')
import pe_readiness
try:
    r=pe_readiness.parse(sys.argv[1])
    print(r['bits'] if r else 0)
except Exception:
    print(0)
PY
)
  [[ "$bits" == "32" ]] || continue
  line=$("$out/test_x86_image" "$f" 2>/dev/null | grep '^REAL PE32')
  traps=$(sed -n 's/.*traps=\([0-9]*\).*/\1/p' <<<"$line")
  rc=$(sed -n 's/.*run_rc=\([0-9]*\).*/\1/p' <<<"$line")
  eax=$(sed -n 's/.*eax=\([0-9]*\).*/\1/p' <<<"$line")
  op=$(sed -n 's/.*last_op=\([0-9a-f]*\).*/\1/p' <<<"$line")
  va=$(sed -n 's/.*fault_va=\([0-9a-f]*\).*/\1/p' <<<"$line")
  printf '| %s | %s | %s | %s | 0x%s | 0x%s |\n' \
    "$(basename "$f")" "$traps" "$rc" "$eax" "$op" "$va" \
    >>docs/pe32-execution-report.md
done
echo "wrote docs/pe32-execution-report.md"
cat docs/pe32-execution-report.md
