#!/bin/bash
# tools/build-hermes.sh — build the Hermes console agent and its upload zip.
#
#   tools/build-hermes.sh [outdir]
#
# Produces:
#   <outdir>/hermes.exe                  freestanding Win64 PE (no CRT)
#   <outdir>/hermes-pkg/hermes.zip       exe + config.ini (Tiramisu /upload)
#
# Env:
#   RELAY_URL   endpoint written into config.ini
#               default http://10.0.0.97:8790/v1/chat/completions
#   HERMES_TASK default task written into config.ini
set -euo pipefail
here="$(cd "$(dirname "$0")/.." && pwd)"; cd "$here"
out="${1:-out}"
mkdir -p "$out" "$out/hermes-pkg"

SDK="${UWP_SDK:-$HOME/.cache/uwp-crossbuild/xwin/sdk}"
CRT="${UWP_CRT:-$HOME/.cache/uwp-crossbuild/xwin/crt}"
CLANG="${CLANG:-clang}"
LLD="${LLD_LINK:-lld-link}"
RELAY_URL="${RELAY_URL:-http://10.0.0.97:8790/v1/chat/completions}"
TASK="${HERMES_TASK:-List the workspace, write a file named proof.txt containing the word native, then read it back and report.}"

[[ -f "$SDK/lib/um/x86_64/kernel32.lib" ]] || { echo "ERROR: xwin SDK missing ($SDK)" >&2; exit 2; }

INC=(-isystem "$CRT/include" -isystem "$SDK/include/ucrt" -isystem "$SDK/include/shared" -isystem "$SDK/include/um")

"$CLANG" --target=x86_64-pc-windows-msvc -O2 -Wall \
  -ffreestanding -fno-builtin -fno-stack-protector -mno-stack-arg-probe \
  -c src/guest/hermes.c -o "$out/hermes.obj"

"$CLANG" --target=x86_64-pc-windows-msvc -O2 -Wall \
  -ffreestanding -fno-builtin -fno-stack-protector -mno-stack-arg-probe \
  "${INC[@]}" -c src/guest/hermes_ui.c -o "$out/hermes_ui.obj"

"$LLD" "$out/hermes.obj" "$out/hermes_ui.obj" /NODEFAULTLIB /ENTRY:hermes_main \
  /SUBSYSTEM:WINDOWS /MACHINE:X64 /DYNAMICBASE \
  /LIBPATH:"$SDK/lib/um/x86_64" \
  kernel32.lib ntdll.lib ws2_32.lib user32.lib d3d11.lib dxgi.lib dxguid.lib \
  /OUT:"$out/hermes.exe"

file "$out/hermes.exe"

pkg="$out/hermes-pkg"
cat > "$pkg/config.ini" <<EOF
# Hermes console agent — generated by tools/build-hermes.sh
endpoint=$RELAY_URL
model=${HERMES_MODEL:-gemini-3.8-flash}
workspace=C:\\\\hermes\\\\workspace
lang=${HERMES_LANG:-en}
token=${HERMES_TOKEN:-}
max_steps=12
task=$TASK
EOF
cp "$out/hermes.exe" "$pkg/hermes.exe"
(cd "$pkg" && rm -f hermes.zip && zip -q hermes.zip hermes.exe config.ini)
ls -l "$pkg/hermes.zip"
echo "built $out/hermes.exe"
