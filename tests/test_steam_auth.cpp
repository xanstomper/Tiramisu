// tests/test_steam_auth.cpp
// Gates for the two Steam modules:
//   * steam_library -- a real VDF parser over real libraryfolders.vdf /
//     appmanifest_*.acf shapes (modern + legacy), plus a filesystem fixture
//     that proves the whole scan path (roots -> manifests -> exe pick).
//   * steam_auth -- OpenID 2.0 assertion parsing/validation with a fake
//     transport, the SteamID64 checks, and the 0600 atomic identity store.
//
// No network is used: trt_steam_set_http_hook() substitutes the transport.
#include "../src/trt/steam_auth.h"
#include "../src/trt/steam_library.h"

#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <string>
#include <vector>

#ifdef _WIN32
#include <windows.h>
#else
#include <sys/stat.h>
#include <unistd.h>
#endif

static int g_fail = 0;
#define CHECK(cond, msg) do { \
    if (cond) { printf("  PASS %s\n", msg); } \
    else { printf("  FAIL %s\n", msg); ++g_fail; } \
} while (0)

static void mkdir_p(const std::string& path) {
#ifdef _WIN32
  CreateDirectoryA(path.c_str(), nullptr);
#else
  mkdir(path.c_str(), 0700);
#endif
}

static void write_text(const std::string& path, const std::string& text) {
  FILE* f = fopen(path.c_str(), "wb");
  if (!f) return;
  fwrite(text.data(), 1, text.size(), f);
  fclose(f);
}

static const char* kModernLibraryVdf =
    "// this file is auto-generated by Steam\n"
    "\"libraryfolders\"\n"
    "{\n"
    "\t\"0\"\n"
    "\t{\n"
    "\t\t\"path\"\t\t\"/tmp/fixture/steam\"\n"
    "\t\t\"label\"\t\t\"\"\n"
    "\t\t\"contentstatsid\"\t\t\"1234567890\"\n"
    "\t\t\"totalsize\"\t\t\"0\"\n"
    "\t}\n"
    "\t\"1\"\n"
    "\t{\n"
    "\t\t\"path\"\t\t\"/tmp/fixture/SteamLibrary\"\n"
    "\t\t\"label\"\t\t\"Games\"\n"
    "\t}\n"
    "}\n";

static const char* kLegacyLibraryVdf =
    "\"LibraryFolders\"\n"
    "{\n"
    "\t\"TimeNextStatsReport\"\t\t\"1670000000\"\n"
    "\t\"ContentStatsID\"\t\t\"-1234\"\n"
    "\t\"1\"\t\t\"/mnt/games/SteamLibrary\"\n"
    "}\n";

static const char* kAppManifest =
    "\"AppState\"\n"
    "{\n"
    "\t\"appid\"\t\t\"730\"\n"
    "\t\"Universe\"\t\t\"1\"\n"
    "\t\"name\"\t\t\"Counter-Strike 2\"\n"
    "\t\"StateFlags\"\t\t\"4\"\n"
    "\t\"installdir\"\t\t\"Counter-Strike Global Offensive\"\n"
    "\t\"SizeOnDisk\"\t\t\"38200000000\"\n"
    "\t\"UserConfig\"\n"
    "\t{\n"
    "\t\t\"language\"\t\t\"english\"\n"
    "\t}\n"
    "}\n";

static std::string fake_steamid_claimed() {
  return "https://steamcommunity.com/openid/id/76561197960287930";
}

static std::string valid_assertion_query() {
  // Field set Steam's provider actually returns, with plausible values.
  std::string q =
      "openid.ns=http%3A%2F%2Fspecs.openid.net%2Fauth%2F2.0"
      "&openid.mode=id_res"
      "&openid.op_endpoint=https%3A%2F%2Fsteamcommunity.com%2Fopenid%2Flogin"
      "&openid.claimed_id=" +
      trt_steam_url_encode(fake_steamid_claimed()) +
      "&openid.identity=" + trt_steam_url_encode(fake_steamid_claimed()) +
      "&openid.return_to=" +
      trt_steam_url_encode("http://10.0.0.171:9127/steam/return") +
      "&openid.response_nonce=2026-11-22T03%3A20%3A00Zabc123"
      "&openid.assoc_handle=1234567890"
      "&openid.signed=signed%2Cop_endpoint%2Cidentity%2Creturn_to%2Cresponse_nonce%2Cassoc_handle%2Cclaimed_id"
      "&openid.sig=deadbeef";
  return q;
}

static bool fake_transport_ok(const std::string& url, const std::string& body,
                              std::string* out, std::string* err) {
  (void)url;
  if (body.find("openid.mode=check_authentication") == std::string::npos) {
    if (err) *err = "hook: mode was not check_authentication";
    return false;
  }
  if (body.find("checkid_setup") != std::string::npos) {
    if (err) *err = "hook: leaked checkid_setup";
    return false;
  }
  // This is the exact body Steam answers a valid assertion with.
  *out = "ns:http://specs.openid.net/auth/2.0\nis_valid:true\n";
  return true;
}

static bool fake_transport_reject(const std::string& url, const std::string& body,
                                  std::string* out, std::string* err) {
  (void)url; (void)body; (void)err;
  *out = "ns:http://specs.openid.net/auth/2.0\nis_valid:false\n";
  return true;
}

static bool fake_transport_down(const std::string& url, const std::string& body,
                                std::string* out, std::string* err) {
  (void)url; (void)body; (void)out;
  if (err) *err = "connection refused";
  return false;
}

int main() {
  const std::string tmp = "/tmp/tiramisu-steam-test";
  mkdir_p(tmp);
  const std::string state_dir = tmp + "/state";
  mkdir_p(state_dir);

  // ---------------------------------------------------------------------
  printf("steam_library: VDF parsing\n");
  {
    std::vector<std::string> paths;
    const int n = trt_steam_parse_library_paths(kModernLibraryVdf, &paths);
    CHECK(n == 2, "modern libraryfolders lists 2 libraries");
    CHECK(paths.size() == 2 && paths[0] == "/tmp/fixture/steam",
          "first library path parsed");
    CHECK(paths.size() == 2 && paths[1] == "/tmp/fixture/SteamLibrary",
          "second library path parsed (label/totalsize skipped)");

    std::vector<std::string> legacy;
    const int ln = trt_steam_parse_library_paths(kLegacyLibraryVdf, &legacy);
    CHECK(ln == 1, "legacy libraryfolders lists 1 library");
    CHECK(legacy.size() == 1 && legacy[0] == "/mnt/games/SteamLibrary",
          "legacy numeric-value form parsed");
    CHECK(legacy.size() == 1 && legacy[0].find("1670000000") == std::string::npos,
          "TimeNextStatsReport not mistaken for a path");

    std::vector<std::string> junk;
    CHECK(trt_steam_parse_library_paths("\"nonsense\" { }", &junk) == -1,
          "a file with no libraryfolders block is rejected");
    CHECK(trt_steam_parse_library_paths("", &junk) == -1,
          "empty text is rejected");

    // A Windows-shaped manifest with escaped backslashes must decode to one
    // backslash per separator, not two.
    std::vector<std::string> win;
    trt_steam_parse_library_paths(
        "\"libraryfolders\"\n{\n \"0\"\n {\n  \"path\" \"D:\\\\SteamLibrary\"\n }\n}\n",
        &win);
    CHECK(win.size() == 1 && win[0] == "D:\\SteamLibrary",
          "escaped backslashes in a VDF path decode once");
  }

  printf("steam_library: split game depots\n");
  {
    const std::string vdf = R"vdf(
      "1000" {
        "config" { "launch" {
          "0" { "executable" "Game.exe" "config" { "oslist" "linux" } }
          "1" { "executable" "Bin\\Game.exe" "workingdir" "." "arguments" "-boot"
                "type" "default" "config" { "oslist" "windows" "osarch" "64" } }
        } }
        "depots" {
          "1002" { "config" { "oslist" "windows" "osarch" "64" }
                   "manifests" { "public" { "gid" "22" "size" "100" } } }
          "1001" { "manifests" { "public" { "gid" "11" "size" "800" } } }
          "1003" { "config" { "language" "english" } "depotfromapp" "900" }
          "1004" { "config" { "oslist" "linux" } "manifests" { "public" "44" } }
          "1005" { "config" { "osarch" "32" } "manifests" { "public" "55" } }
          "1006" { "config" { "language" "french" } "manifests" { "public" "66" } }
          "1007" { "dlcappid" "2000" "manifests" { "public" "77" } }
          "228980" { "manifests" { "public" "88" } }
        }
      })vdf";
    trt_steam_app_content content;
    const bool parsed = trt_steam_parse_app_content(std::string("\x01\0", 2) + vdf, &content);
    CHECK(parsed && content.depots.size() == 4 &&
              content.depots[0].id == 1001 && content.depots[1].id == 1002,
          "base assets and Windows executables are both selected in overlay order");
    CHECK(parsed && content.depots.size() == 4 &&
              content.depots[2].source_app == 900 && content.depots[2].manifest == 0 &&
              content.depots[3].optional_dlc,
          "shared and optional DLC depots retain their source and license status");
    CHECK(content.executable == "Bin\\Game.exe" && content.working_dir == "." &&
              content.arguments == "-boot",
          "Windows launch entry carries the exe, working directory, and arguments");

    trt_steam_depot shared;
    CHECK(trt_steam_find_public_depot(
              R"("depots" { "1003" { "manifests" { "public" "33" } } })", 1003, &shared) &&
              shared.manifest == 33,
          "shared depot looks up its public manifest from the source app");

    trt_steam_depot_layout layout;
    CHECK(trt_steam_add_depot_path(layout, "Content\\Assets.pak", {0, 0, false}) &&
              trt_steam_add_depot_path(layout, "Bin\\Game.exe", {1, 0, false}) &&
              trt_steam_add_depot_path(layout, "content\\ASSETS.pak", {2, 0, false}) &&
              trt_steam_validate_depot_layout(layout, nullptr) &&
              layout.size() == 2 && layout.at("bin\\game.exe").depot == 1 &&
              layout.at("content\\assets.pak").depot == 2,
          "the merged install keeps the executable and resolves an asset overlay once");
    CHECK(!trt_steam_add_depot_path(layout, "Bin\\Game.exe", {0, 1, true}),
          "a depot cannot convert an existing file into a directory");
    trt_steam_add_depot_path(layout, "Bin\\Game.exe\\bad", {2, 1, false});
    std::string conflict;
    CHECK(!trt_steam_validate_depot_layout(layout, &conflict) && conflict == "bin\\game.exe",
          "a merged file cannot also be a parent directory");

    std::string path;
    CHECK(trt_steam_normalize_content_path("./Bin/Game.exe", &path) && path == "Bin\\Game.exe" &&
              !trt_steam_normalize_content_path("Bin/../Game.exe", &path) &&
              !trt_steam_normalize_content_path("C:/Game.exe", &path),
          "Windows depot paths normalize beneath the game root");
  }

  printf("steam_library: appmanifest parsing\n");
  {
    trt_steam_app app;
    CHECK(trt_steam_parse_appmanifest(kAppManifest, &app) == 0,
          "appmanifest_730.acf parsed");
    CHECK(app.appid == 730, "appid read");
    CHECK(app.name == "Counter-Strike 2", "name read (spaces preserved)");
    CHECK(app.installdir == "Counter-Strike Global Offensive",
          "installdir read");
    CHECK(app.size_on_disk == 38200000000ull, "SizeOnDisk read as 64-bit");
    CHECK(app.fully_installed, "StateFlags 4 -> fully installed");

    trt_steam_app noappid;
    CHECK(trt_steam_parse_appmanifest("\"AppState\" { \"name\" \"x\" }",
                                      &noappid) == -1,
          "manifest without appid is rejected");
  }

  printf("steam_library: filesystem scan\n");
  {
    const std::string lib = tmp + "/lib";
    const std::string steamapps = lib + "/steamapps";
    const std::string game = lib + "/steamapps/common/Counter-Strike Global Offensive";
    mkdir_p(tmp);
    mkdir_p(lib);
    mkdir_p(steamapps);
    mkdir_p(lib + "/steamapps/common");
    mkdir_p(game);
    write_text(steamapps + "/appmanifest_730.acf", kAppManifest);
    write_text(steamapps + "/appmanifest_228980.acf",
               "\"AppState\"\n{\n \"appid\" \"228980\"\n \"name\" \"Steamworks Common\"\n"
               " \"StateFlags\" \"2\"\n \"installdir\" \"Steamworks Shared\"\n}\n");
    write_text(steamapps + "/libraryfolders.vdf",
               std::string("\"libraryfolders\"\n{\n \"0\"\n {\n  \"path\" \"") +
                   lib + "\"\n }\n}\n");
    // Two exes: the named one must win even though it is smaller.
    write_text(game + "/cs2.exe", "small-launcher");
    write_text(game + "/hl2.exe", "a much larger binary body goes here");

    trt_steam_library L;
    const int count = trt_steam_library_scan_roots({lib}, &L);
    CHECK(count == 2, "scan found both manifests");
    CHECK(L.roots.size() == 1 && L.roots[0] == lib, "root recorded");
    bool have730 = false, have228980 = false;
    for (const auto& a : L.apps) {
      if (a.appid == 730) {
        have730 = a.fully_installed && a.library_path == lib;
      }
      if (a.appid == 228980) {
        have228980 = !a.fully_installed;  // StateFlags 2 = update required
      }
    }
    CHECK(have730, "app 730 present, fully installed, bound to its library");
    CHECK(have228980, "app 228980 present and NOT reported as installed");

    // No exe name matches the install-dir name here, so the largest wins.
    const std::string exe = trt_steam_find_exe(game);
    CHECK(exe == "hl2.exe", "find_exe picks the largest exe when none matches");

    // ...and a name match beats size.
    const std::string rl = lib + "/steamapps/common/RocketLeague";
    mkdir_p(rl);
    write_text(rl + "/rocketleague.exe", "tiny");
    write_text(rl + "/helper.exe", "a considerably larger helper binary");
    CHECK(trt_steam_find_exe(rl) == "rocketleague.exe",
          "find_exe prefers the exe named after the game");

    CHECK(trt_steam_find_exe(steamapps) == "",
          "find_exe returns empty for a dir with no exe");
  }

  printf("steam_auth: encoding and URL\n");
  {
    const std::string round = trt_steam_url_decode(
        trt_steam_url_encode("a b&c=d/e?f#g:+%"));
    CHECK(round == "a b&c=d/e?f#g:+%", "url encode/decode round-trips");
    CHECK(trt_steam_url_encode("http://x/y") == "http%3A%2F%2Fx%2Fy",
          "encode escapes : and /");

    const std::string url = trt_steam_login_url(
        "http://10.0.0.171:9127/steam/return", "http://10.0.0.171:9127");
    CHECK(url.rfind("https://steamcommunity.com/openid/login?", 0) == 0,
          "login url targets Steam's endpoint");
    CHECK(url.find("openid.mode=checkid_setup") != std::string::npos,
          "login url asks for checkid_setup");
    CHECK(url.find("openid.return_to=http%3A%2F%2F10.0.0.171%3A9127%2Fsteam%2Freturn") !=
              std::string::npos,
          "return_to is encoded");
    CHECK(url.find("identifier_select") != std::string::npos,
          "identity/claimed_id use identifier_select");
  }

  printf("steam_auth: assertion validation\n");
  {
    std::map<std::string, std::string> params;
    std::string err;
    CHECK(trt_steam_parse_assertion(valid_assertion_query(), &params, &err) == 0,
          "well-formed Steam assertion accepted");

    std::map<std::string, std::string> dup;
    CHECK(!trt_steam_parse_query("a=1&a=2", &dup, &err),
          "duplicate parameter rejected");
    CHECK(err.find("duplicate") != std::string::npos, "duplicate error named");

    // Each of these must fail loudly.
    auto expect_fail = [&](const std::string& q, const char* what) {
      std::map<std::string, std::string> p;
      std::string e;
      const bool failed = trt_steam_parse_assertion(q, &p, &e) != 0;
      printf("  %s %s%s%s\n", failed ? "PASS" : "FAIL", what,
             failed && !e.empty() ? " -> " : "", e.c_str());
      if (!failed) ++g_fail;
    };
    expect_fail("openid.ns=x&openid.mode=id_res", "missing fields rejected");
    {
      std::string q = valid_assertion_query();
      const size_t p = q.find("openid.mode=id_res");
      q.replace(p, strlen("openid.mode=id_res"), "openid.mode=cancel");
      expect_fail(q, "mode=cancel rejected (user declined)");
    }
    {
      std::string q = valid_assertion_query();
      const size_t p = q.find("openid.op_endpoint=");
      const size_t amp = q.find('&', p);
      q.replace(p, amp - p, "openid.op_endpoint=https%3A%2F%2Fevil.example%2Flogin");
      expect_fail(q, "foreign op_endpoint rejected");
    }
    {
      std::string q = valid_assertion_query();
      const size_t p = q.find("openid.claimed_id=");
      const size_t amp = q.find('&', p);
      q.replace(p, amp - p, "openid.claimed_id=https%3A%2F%2Fsteamcommunity.com%2Fopenid%2Fid%2F123");
      expect_fail(q, "short/garbage claimed_id rejected");
    }

    std::string steamid;
    CHECK(trt_steam_claimed_id_to_steam64(fake_steamid_claimed(), &steamid),
          "valid SteamID64 extracted");
    CHECK(steamid == "76561197960287930", "steamid64 matches input");
    CHECK(!trt_steam_claimed_id_to_steam64(
              "https://steamcommunity.com/openid/id/26561197960287930",
              &steamid),
          "wrong Universe bit rejected");
    CHECK(!trt_steam_claimed_id_to_steam64(
              "https://evil.example/openid/id/76561197960287930", &steamid),
          "non-Steam claimed_id origin rejected");
    CHECK(!trt_steam_claimed_id_to_steam64(
              "https://steamcommunity.com/openid/id/7656119796028793a", &steamid),
          "non-digit steamid rejected");

    const std::string body = trt_steam_validation_body(params);
    CHECK(body.find("openid.mode=check_authentication") != std::string::npos,
          "validation body swaps mode");
    CHECK(body.find("openid.sig=deadbeef") != std::string::npos,
          "validation body carries the signature");
    CHECK(body.find("checkid_setup") == std::string::npos,
          "validation body has no checkid_setup");

    CHECK(trt_steam_validation_ok("ns:x\nis_valid:true\n"), "is_valid:true accepted");
    CHECK(!trt_steam_validation_ok("ns:x\nis_valid:false\n"), "is_valid:false rejected");
    CHECK(!trt_steam_validation_ok("ns:x\nis_valid:\n"), "empty is_valid rejected");
    CHECK(!trt_steam_validation_ok(""), "empty response rejected");

    std::string out, e2;
    CHECK(!trt_steam_http_post("https://evil.example/openid/login", "x", &out, &e2),
          "post to a non-Steam endpoint refused");
  }

  printf("steam_auth: sign-in, persistence, sign-out\n");
  {
    trt_steam_identity id;
    std::string err;

    trt_steam_set_http_hook(fake_transport_down);
    CHECK(trt_steam_auth_complete(state_dir, valid_assertion_query(), &id, &err) == -1,
          "transport failure fails sign-in");
    CHECK(trt_steam_auth_load(state_dir, &id) == false,
          "nothing persisted after a transport failure");

    trt_steam_set_http_hook(fake_transport_reject);
    CHECK(trt_steam_auth_complete(state_dir, valid_assertion_query(), &id, &err) == -1,
          "Steam rejecting the assertion fails sign-in");
    CHECK(!trt_steam_auth_load(state_dir, &id),
          "nothing persisted after a rejected assertion");

    trt_steam_set_http_hook(fake_transport_ok);
    CHECK(trt_steam_auth_complete(state_dir, valid_assertion_query(), &id, &err) == 0,
          "validated assertion signs in");
    CHECK(id.steamid64 == "76561197960287930", "identity carries the SteamID");
    CHECK(id.signed_in_at > 0, "sign-in timestamp recorded");

    trt_steam_identity loaded;
    CHECK(trt_steam_auth_load(state_dir, &loaded), "identity reloads from disk");
    CHECK(loaded.steamid64 == "76561197960287930", "reloaded SteamID matches");
    CHECK(loaded.method == "openid2", "reloaded method recorded");

#ifndef _WIN32
    struct stat st;
    const std::string path = trt_steam_state_path(state_dir);
    CHECK(stat(path.c_str(), &st) == 0 && (st.st_mode & 0777) == 0600,
          "identity file is 0600");
#endif

    // No password or token may ever reach the file.
    {
      FILE* f = fopen(trt_steam_state_path(state_dir).c_str(), "rb");
      std::string text;
      if (f) {
        char buf[512];
        size_t n;
        while ((n = fread(buf, 1, sizeof(buf), f)) > 0) text.append(buf, n);
        fclose(f);
      }
      // "signed_in_at" legitimately contains "signed"; look for the OpenID
      // assertion fields and any credential-shaped key instead.
      CHECK(text.find("openid.") == std::string::npos &&
                text.find("assoc_handle") == std::string::npos &&
                text.find("response_nonce") == std::string::npos &&
                text.find("password") == std::string::npos &&
                text.find("token") == std::string::npos &&
                text.find("cookie") == std::string::npos,
            "state file holds no assertion, signature or secret");
    }

    // A hand-edited file with a bogus SteamID must be refused, not trusted.
    write_text(trt_steam_state_path(state_dir),
               "{\"steamid64\": \"11111111111111111\", \"signed_in_at\": 1}\n");
    CHECK(!trt_steam_auth_load(state_dir, &loaded),
          "tampered identity file rejected on load");

    trt_steam_set_http_hook(fake_transport_ok);
    CHECK(trt_steam_auth_complete(state_dir, valid_assertion_query(), &id, &err) == 0,
          "re-sign-in after tamper works");
    CHECK(trt_steam_auth_sign_out(state_dir), "sign-out removes the identity");
    CHECK(!trt_steam_auth_load(state_dir, &loaded), "signed out afterwards");

    trt_steam_set_http_hook(nullptr);
  }

  printf("\nRESULT: %s (%d failures)\n", g_fail ? "FAIL" : "ALL PASS", g_fail);
  return g_fail ? 1 : 0;
}
